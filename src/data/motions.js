// 画像がそろっていてお手本アニメを出せる種目か
export function hasMotion(id) {
  const m = MOTIONS[id]
  const imgs = MOTION_IMAGES[id]
  return !!(m && imgs && m.seq.every((f) => imgs[f.i]))
}
